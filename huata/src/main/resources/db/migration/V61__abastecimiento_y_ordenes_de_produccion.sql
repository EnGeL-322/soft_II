-- V61: flujo del prototipo de produccion aprobado por el cliente (2026-10-28).
--
-- 1) La compra ya no es stock: se registra PENDIENTE_RECEPCION y la RECEPCION (total o parcial, con
--    lote y vencimiento del proveedor) es la que mete el insumo al almacen y su asiento. Una compra
--    al contado que llega con la factura se recibe en el mismo acto ("recibir ahora").
-- 2) Orden de produccion (OP): se planifica aunque falte stock; su estado "lista / esperando
--    insumos" se calcula en vivo contra el almacen y se cumple al registrar el lote.
-- 3) Maestro de insumos: tipo (materia prima, insumo, empaque) y sinonimos para buscar.
--
-- Nada historico cambia de significado: las compras ya registradas entraron al almacen al
-- registrarse, asi que quedan RECIBIDA con todo lo comprado como recibido, sin recepcion propia.

-- 1) Compras y recepciones -----------------------------------------------------------------------
ALTER TABLE public.compras ADD COLUMN estado character varying(30) NOT NULL DEFAULT 'RECIBIDA';
ALTER TABLE public.compras ADD CONSTRAINT compras_estado_check
    CHECK (estado IN ('PENDIENTE_RECEPCION', 'RECIBIDA_PARCIAL', 'RECIBIDA'));
ALTER TABLE public.compras ALTER COLUMN estado DROP DEFAULT;
CREATE INDEX compras_estado_idx ON public.compras (estado) WHERE activo;

ALTER TABLE public.compra_items ADD COLUMN cantidad_recibida numeric(12, 4) NOT NULL DEFAULT 0;
UPDATE public.compra_items SET cantidad_recibida = cantidad;
ALTER TABLE public.compra_items ALTER COLUMN cantidad_recibida DROP DEFAULT;
ALTER TABLE public.compra_items ADD CONSTRAINT compra_items_recibida_valida
    CHECK (cantidad_recibida >= 0 AND cantidad_recibida <= cantidad);

CREATE TABLE public.recepciones_compra (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo boolean NOT NULL DEFAULT true,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone,
    created_by character varying(120),
    updated_by character varying(120),
    compra_id bigint NOT NULL,
    fecha date NOT NULL,
    documento character varying(60),
    CONSTRAINT recepciones_compra_compra_fk FOREIGN KEY (compra_id) REFERENCES public.compras (id)
);
CREATE INDEX recepciones_compra_compra_idx ON public.recepciones_compra (compra_id);
COMMENT ON TABLE public.recepciones_compra IS
    'Lo que realmente llego de una compra. Cada recepcion mete sus cantidades al almacen (kardex '
    'ENTRADA_COMPRA) y registra su asiento por el valor recibido.';

CREATE TABLE public.recepcion_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo boolean NOT NULL DEFAULT true,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone,
    created_by character varying(120),
    updated_by character varying(120),
    recepcion_id bigint NOT NULL,
    compra_item_id bigint NOT NULL,
    cantidad numeric(12, 4) NOT NULL,
    lote character varying(60),
    fecha_vencimiento date,
    CONSTRAINT recepcion_items_recepcion_fk FOREIGN KEY (recepcion_id) REFERENCES public.recepciones_compra (id),
    CONSTRAINT recepcion_items_compra_item_fk FOREIGN KEY (compra_item_id) REFERENCES public.compra_items (id),
    CONSTRAINT recepcion_items_cantidad_positiva CHECK (cantidad > 0)
);
CREATE INDEX recepcion_items_recepcion_idx ON public.recepcion_items (recepcion_id);
CREATE INDEX recepcion_items_vencimiento_idx ON public.recepcion_items (fecha_vencimiento) WHERE fecha_vencimiento IS NOT NULL;

-- 2) Ordenes de produccion -----------------------------------------------------------------------
CREATE TABLE public.ordenes_produccion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo boolean NOT NULL DEFAULT true,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone,
    created_by character varying(120),
    updated_by character varying(120),
    codigo character varying(20) NOT NULL,
    producto_id bigint NOT NULL,
    receta_id bigint NOT NULL,
    cantidad integer NOT NULL,
    fecha_plan date NOT NULL,
    estado character varying(20) NOT NULL,
    lote_id bigint,
    observaciones character varying(500),
    motivo_anulacion character varying(300),
    CONSTRAINT ordenes_produccion_codigo_uk UNIQUE (codigo),
    CONSTRAINT ordenes_produccion_producto_fk FOREIGN KEY (producto_id) REFERENCES public.productos (id),
    CONSTRAINT ordenes_produccion_receta_fk FOREIGN KEY (receta_id) REFERENCES public.recetas_queso (id),
    CONSTRAINT ordenes_produccion_lote_fk FOREIGN KEY (lote_id) REFERENCES public.lotes_queso (id),
    CONSTRAINT ordenes_produccion_cantidad_positiva CHECK (cantidad > 0),
    CONSTRAINT ordenes_produccion_estado_check CHECK (estado IN ('PENDIENTE', 'TERMINADA', 'ANULADA')),
    CONSTRAINT ordenes_produccion_terminada_con_lote CHECK ((estado = 'TERMINADA') = (lote_id IS NOT NULL))
);
CREATE INDEX ordenes_produccion_estado_idx ON public.ordenes_produccion (estado, fecha_plan);
COMMENT ON TABLE public.ordenes_produccion IS
    'Produccion planificada (OP). Si esta lista o espera insumos no se guarda: se calcula contra el '
    'almacen al consultarla. Se cumple al registrar el lote que la referencia.';

-- 3) Maestro de insumos --------------------------------------------------------------------------
ALTER TABLE public.materias_primas ADD COLUMN tipo character varying(20) NOT NULL DEFAULT 'MATERIA_PRIMA';
ALTER TABLE public.materias_primas ADD CONSTRAINT materias_primas_tipo_check
    CHECK (tipo IN ('MATERIA_PRIMA', 'INSUMO', 'EMPAQUE'));
ALTER TABLE public.materias_primas ADD COLUMN sinonimos character varying(300);
