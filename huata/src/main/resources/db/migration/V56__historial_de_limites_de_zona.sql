-- V56: historial de los limites (poligonos) de zona.
--
-- Pedido del cliente (2026-10-25): borro un poligono por accidente y no habia como recuperarlo:
-- guardar y eliminar un limite reemplazaba/borraba sus vertices sin dejar copia. Desde ahora,
-- antes de cada cambio o eliminacion se guarda aqui la version anterior completa (zona, color y
-- vertices), y desde "Rutas y mapa" se puede restaurar cualquiera de ellas.
--
-- Los vertices van como JSON [[lat, lng], ...] en texto: es una foto para restaurar, no se consulta
-- por coordenada.

CREATE TABLE public.zona_poligono_versiones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo boolean NOT NULL DEFAULT true,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone,
    created_by character varying(120),
    updated_by character varying(120),
    zona character varying(120) NOT NULL,
    color character varying(20),
    vertices text NOT NULL,
    motivo character varying(40) NOT NULL
);

CREATE INDEX zona_poligono_versiones_zona_idx ON public.zona_poligono_versiones (lower(zona), created_at DESC);

COMMENT ON TABLE public.zona_poligono_versiones IS
    'Copia del limite de una zona tomada justo antes de modificarlo o eliminarlo, para poder restaurarlo.';
COMMENT ON COLUMN public.zona_poligono_versiones.motivo IS
    'Que se hizo despues de tomar la copia: MODIFICADO, ELIMINADO, ZONA_ELIMINADA o RESTAURADO.';
