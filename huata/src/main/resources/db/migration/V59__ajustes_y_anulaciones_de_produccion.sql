-- V59: el flujo de produccion se puede corregir sin tocar movimientos ya escritos (2026-10-27).
--
-- Hasta ahora un error no tenia salida: el stock de un insumo no se podia ajustar (merma, conteo
-- fisico, leche descartada) aunque el propio sistema lo pedia ("corrija con un ajuste de
-- inventario"), y un lote o una compra registrados por error no se podian anular. Las tres cosas se
-- resuelven con movimientos nuevos (AJUSTE_ENTRADA / AJUSTE_SALIDA, que ya existen en el kardex) y
-- asientos de reversion: nada se edita ni se borra.

-- 1) Ajuste de inventario: el documento que explica cada AJUSTE manual del kardex.
CREATE TABLE public.ajustes_inventario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo boolean NOT NULL DEFAULT true,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone,
    created_by character varying(120),
    updated_by character varying(120),
    materia_prima_id bigint NOT NULL,
    tipo character varying(10) NOT NULL,
    cantidad numeric(12, 4) NOT NULL,
    fecha date NOT NULL,
    motivo character varying(300) NOT NULL,
    CONSTRAINT ajustes_inventario_materia_prima_fk FOREIGN KEY (materia_prima_id) REFERENCES public.materias_primas (id),
    CONSTRAINT ajustes_inventario_tipo_check CHECK (tipo IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT ajustes_inventario_cantidad_positiva CHECK (cantidad > 0)
);
CREATE INDEX ajustes_inventario_materia_prima_idx ON public.ajustes_inventario (materia_prima_id, fecha);
COMMENT ON TABLE public.ajustes_inventario IS
    'Ajuste manual de stock de una materia prima (merma, conteo fisico, leche descartada) con su motivo. '
    'El stock lo mueve el movimiento AJUSTE_ENTRADA/AJUSTE_SALIDA que apunta a esta fila.';

-- 2) Anular un lote o una compra deja la fila (activo = false) con el motivo.
ALTER TABLE public.lotes_queso ADD COLUMN motivo_anulacion character varying(300);
ALTER TABLE public.compras ADD COLUMN motivo_anulacion character varying(300);

-- 3) Asientos de los ajustes y de las reversiones.
ALTER TABLE public.asientos_contables DROP CONSTRAINT asientos_contables_origen_check;
ALTER TABLE public.asientos_contables ADD CONSTRAINT asientos_contables_origen_check CHECK (origen_tipo IN (
    'COMPRA', 'PRODUCCION_CONSUMO', 'PRODUCCION_MANO_OBRA', 'PRODUCCION_TERMINADO',
    'VENTA', 'VENTA_COSTO', 'ANULACION_VENTA', 'LIQUIDACION_PAGO', 'LIQUIDACION_REAPERTURA',
    'RECEPCION_LECHE', 'AJUSTE_INVENTARIO', 'ANULACION_PRODUCCION', 'ANULACION_COMPRA'));
