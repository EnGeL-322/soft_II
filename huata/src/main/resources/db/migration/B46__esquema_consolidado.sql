-- Inicio: V18__sincronizar_reasignaciones_de_zona.sql
-- ===========================================================================
-- Repara solicitudes aprobadas por la version anterior, que cambiaba solo zona_principal y dejaba
-- la ruta/acopiador antiguos. Una zona puede ser una parte de una ruta compuesta ("A / B").
WITH destinos AS (
    SELECT DISTINCT ON (p.id)
           p.id AS productor_id,
           r.id AS ruta_id,
           r.zona
    FROM productores p
    JOIN rutas r ON r.activo
      AND (
          lower(btrim(r.zona)) = lower(btrim(p.zona_principal))
          OR EXISTS (
              SELECT 1
              FROM unnest(string_to_array(r.zona, '/')) parte
              WHERE lower(btrim(parte)) = lower(btrim(p.zona_principal))
          )
      )
    WHERE p.activo
      AND p.zona_principal IS NOT NULL
    ORDER BY p.id, r.id
)
UPDATE productores p
SET ruta_id = d.ruta_id,
    zona_principal = d.zona,
    updated_at = now()
FROM destinos d
WHERE p.id = d.productor_id
  AND (p.ruta_id IS DISTINCT FROM d.ruta_id OR p.zona_principal IS DISTINCT FROM d.zona);

UPDATE productores p
SET acopiador_responsable_id = (
        SELECT a.id
        FROM acopiadores a
        WHERE a.activo AND a.ruta_id = p.ruta_id
        ORDER BY a.nombres, a.id
        LIMIT 1
    ),
    updated_at = now()
WHERE p.activo
  AND p.ruta_id IS NOT NULL
  AND (
      p.acopiador_responsable_id IS NULL
      OR NOT EXISTS (
          SELECT 1 FROM acopiadores a
          WHERE a.id = p.acopiador_responsable_id AND a.activo AND a.ruta_id = p.ruta_id
      )
  );

