        (tipo = 'DIA' AND fecha IS NOT NULL) OR (tipo = 'PREDETERMINADO' AND fecha IS NULL)
    )
);
COMMENT ON TABLE public.trazados_acopiador IS
    'Recorrido que pinta el acopiador en la app. tipo=DIA es el de una fecha concreta; '
