-- Inicio: V1__esquema_inicial.sql
-- ===========================================================================
-- V1: esquema inicial de Huata Lacteos.
--
-- ORIGEN: generado con pg_dump --schema-only sobre una base PostgreSQL 17 creada por Hibernate a
-- partir de las 21 entidades JPA existentes (22 tablas: 21 entidades + la tabla puente
-- usuario_roles). No esta escrito a mano, y eso es a proposito: garantiza que coincide exactamente
-- con el mapeo, que es justo lo que a partir de ahora comprueba ddl-auto=validate al arrancar.
--
-- A PARTIR DE AQUI el esquema NO se toca con ddl-auto. Todo cambio va en una migracion nueva
-- (V2, V3, ...) y nunca editando este archivo: Flyway valida el checksum de las ya aplicadas.
--
-- DEUDA CONOCIDA: los nombres de clave foranea (fk<hash>) los genero Hibernate y son ilegibles.
-- Renombrarlos es seguro pero ruidoso; se deja para cuando haya que tocar esas tablas.

