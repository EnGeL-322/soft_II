-- Esquema consolidado de Huata Lacteos hasta la version 50.
--
-- Reune las 46 migraciones historicas V1..V50 en su orden numerico original.
-- Los bloques conservan sus sentencias SQL y datos de catalogo sin cambios.
-- Flyway ejecuta esta migracion baseline una sola vez al inicializar una base nueva.
-- Las siguientes migraciones deben continuar con V51, V52, ...
--
-- Uso: base PostgreSQL nueva y vacia. No ejecutar sobre una base ya poblada.
-- Las bases con historial V1..V50 requieren una transicion de historial antes de
-- usar este conjunto consolidado; ver ESTRUCTURA_BASE_DATOS.md.

