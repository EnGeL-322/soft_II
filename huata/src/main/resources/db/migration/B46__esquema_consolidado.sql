-- Inicio: V4__liquidacion_unica_por_periodo.sql
-- ===========================================================================
-- V4: impedir dos liquidaciones activas del mismo proveedor y periodo.
--
-- EL FALLO: LiquidacionService.calcular() buscaba la liquidacion existente con
--   .filter(estado != CLOSED).orElseGet(Liquidacion::new)
-- de modo que recalcular un periodo YA CERRADO no reutilizaba la existente: descartaba la cerrada y
-- creaba una segunda para el mismo proveedor y la misma semana. Consecuencias:
--   - el proveedor quedaba con dos liquidaciones de la misma semana;
--   - los reportes sumaban dos veces sus litros y su importe;
--   - findByProductorIdAndPeriodoInicioAndPeriodoFin devuelve Optional, asi que a partir del
--     duplicado esa consulta empezaba a fallar por resultado no unico.
--
-- El codigo ya rechaza recalcular un periodo cerrado. Esto es la otra mitad: la garantia en la base,
-- que ademas cubre el caso de dos peticiones simultaneas, donde la comprobacion en Java no basta.

-- 1) Se INACTIVAN los duplicados que ya existan, no se borran: BaseEntity fija que los registros de
--    negocio (y nombra las liquidaciones) no se eliminan fisicamente. Asi queda rastro de lo que
--    paso en vez de desaparecer el dia de la migracion.
--
--    Se conserva la CLOSED, que es la que se pago de verdad; si ninguna lo esta, la mas antigua.
WITH ordenadas AS (
    SELECT id,
           row_number() OVER (
               PARTITION BY productor_id, periodo_inicio, periodo_fin
               ORDER BY (estado = 'CLOSED') DESC, id ASC
           ) AS posicion
    FROM public.liquidaciones
    WHERE activo = true
)
UPDATE public.liquidaciones l
SET activo = false,
    updated_at = now(),
    updated_by = 'migracion V4'
FROM ordenadas o
WHERE l.id = o.id
  AND o.posicion > 1;

-- 2) Indice unico PARCIAL: solo sobre las activas. Una liquidacion inactivada por el paso anterior
--    (o inactivada a mano en el futuro) no bloquea que se vuelva a liquidar ese periodo.
CREATE UNIQUE INDEX liquidaciones_periodo_unico
    ON public.liquidaciones (productor_id, periodo_inicio, periodo_fin)
    WHERE activo = true;

