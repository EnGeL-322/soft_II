-- Inicio: V47__calidad_en_campo_y_en_planta.sql
-- ===========================================================================
-- Calidad medida en campo (testeador) o en planta, con o sin recojo (2026-10-14).
--
-- Hay dos caminos para la leche:
--   * Entrega directa: el proveedor lleva su leche a planta; ahi se analiza y se recibe.
--   * Acopio en ruta: el TESTEADOR pasa ANTES que el acopiador y analiza la leche donde el
--     proveedor; despues el acopiador la recoge con la app.
-- En el segundo caso el control existe antes que el recojo. Hasta ahora controles_calidad.recojo_id
-- era obligatorio, asi que la app del testeador exigia que el acopiador hubiera pasado primero
-- (ver huata_app/lib/features/testeador/voucher_screen.dart). El control pasa a colgar del
-- proveedor y la fecha, y el recojo se vincula cuando existe.

ALTER TABLE controles_calidad ADD COLUMN productor_id BIGINT;
ALTER TABLE controles_calidad ADD COLUMN fecha_hora TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE controles_calidad ADD COLUMN lugar_analisis VARCHAR(20);

-- Los controles existentes heredan proveedor y fecha de su recojo.
UPDATE controles_calidad c
SET productor_id = r.productor_id,
    fecha_hora = r.fecha_hora
FROM recojos r
WHERE r.id = c.recojo_id;

-- Lugar: solo se sabe con certeza para las entregas directas (fuente PLANTA). En los recojos de
-- ruta no consta si se midio en campo o al llegar a planta: queda NULL ("sin dato"), no se inventa.
UPDATE controles_calidad c
SET lugar_analisis = 'PLANTA'
FROM recojos r
WHERE r.id = c.recojo_id
  AND r.fuente = 'PLANTA';

ALTER TABLE controles_calidad ALTER COLUMN productor_id SET NOT NULL;
ALTER TABLE controles_calidad ALTER COLUMN fecha_hora SET NOT NULL;
ALTER TABLE controles_calidad ALTER COLUMN recojo_id DROP NOT NULL;

ALTER TABLE controles_calidad
    ADD CONSTRAINT fk_controles_calidad_productor FOREIGN KEY (productor_id) REFERENCES productores (id);
ALTER TABLE controles_calidad
    ADD CONSTRAINT controles_calidad_lugar_analisis_check CHECK (lugar_analisis IN ('CAMPO', 'PLANTA'));

-- Historial por proveedor y busqueda del control de campo del dia que espera su recojo.
CREATE INDEX idx_controles_calidad_productor_fecha ON controles_calidad (productor_id, fecha_hora);

COMMENT ON COLUMN controles_calidad.recojo_id IS
    'Recojo analizado. Nulo mientras un control de campo (testeador) espera que el acopiador registre el recojo de ese proveedor y dia.';
COMMENT ON COLUMN controles_calidad.productor_id IS
    'Proveedor cuya leche se analizo. Igual al productor del recojo cuando hay recojo.';
COMMENT ON COLUMN controles_calidad.fecha_hora IS
    'Momento del analisis. En controles anteriores a V47 es la fecha del recojo.';
COMMENT ON COLUMN controles_calidad.lugar_analisis IS
    'CAMPO (testeador, antes del acopiador) o PLANTA (entrega directa o muestra analizada en planta). Nulo en controles anteriores a V47 de recojos de ruta: no consta donde se midieron.';


