-- Inicio: V48__aprobacion_de_calidad_y_recepcion_del_testeador.sql
-- ===========================================================================
-- Calidad se registra en la app y se aprueba en la web (decision del cliente, 2026-10-14).
--
--   * Solo la app movil registra analisis de calidad (con OCR del voucher): el testeador en campo,
--     antes del acopiador, y tambien al recibir en planta una entrega directa.
--   * La web no registra analisis: los APRUEBA. Quien aprueba es otra persona que quien analizo,
--     por eso es un permiso aparte (calidad.aprobar) y no calidad.write, que tiene el testeador.

ALTER TABLE controles_calidad ADD COLUMN aprobado_por VARCHAR(120);
ALTER TABLE controles_calidad ADD COLUMN aprobado_en TIMESTAMP(6) WITH TIME ZONE;

COMMENT ON COLUMN controles_calidad.aprobado_por IS
    'Usuario que aprobo el analisis en la web. Nulo = pendiente de aprobacion. Se borra si el analisis se corrige despues.';
COMMENT ON COLUMN controles_calidad.aprobado_en IS
    'Momento de la aprobacion. Nulo = pendiente de aprobacion.';

CREATE INDEX idx_controles_calidad_por_aprobar ON controles_calidad (fecha_hora) WHERE aprobado_en IS NULL;

INSERT INTO permisos (codigo, recurso, accion, descripcion) VALUES
  ('calidad.aprobar', 'calidad', 'aprobar', 'Aprobar en la web los analisis registrados con la app')
ON CONFLICT (codigo) DO NOTHING;

-- Aprueban: el analista de calidad y el supervisor de planta.
-- El testeador ademas recibe en planta entregas directas con su analisis (planta.recepcion).
INSERT INTO rol_permisos (rol_id, permiso_id)
SELECT r.id, p.id FROM roles r CROSS JOIN permisos p
WHERE (r.nombre IN ('CALIDAD', 'SUPERVISOR_PLANTA') AND p.codigo = 'calidad.aprobar')
   OR (r.nombre = 'TESTEADOR' AND p.codigo = 'planta.recepcion')
ON CONFLICT DO NOTHING;

INSERT INTO vista_acciones (vista_id, permiso_id, etiqueta, orden)
SELECT v.id, p.id, 'Aprobar análisis', 30
FROM vistas v JOIN permisos p ON p.codigo = 'calidad.aprobar'
WHERE v.codigo = 'calidad'
  AND NOT EXISTS (SELECT 1 FROM vista_acciones a WHERE a.vista_id = v.id AND a.permiso_id = p.id);


